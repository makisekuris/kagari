// Package textclip bounds displayed text by Unicode code points.
package textclip

// Truncate counts the ellipsis within the limit.
func Truncate(value string, limit int) string {
	if limit <= 0 {
		return ""
	}
	runes := []rune(value)
	if len(runes) <= limit {
		return value
	}
	return string(runes[:limit-1]) + "…"
}

func Limit(value string, limit int) string {
	runes := []rune(value)
	if len(runes) > limit {
		return string(runes[:limit])
	}
	return value
}

// Excerpt appends the retrieval notice outside the body limit.
func Excerpt(value string, limit int) string {
	runes := []rune(value)
	if len(runes) <= limit {
		return value
	}
	return string(runes[:limit]) + "\n（节选；完整内容可通过工具查询。）"
}
